    /// <summary>One page of the in-game rulebook: a heading, the text of the page and the rule reference.</summary>
    public sealed record RulesSection(string Id, string Title, IReadOnlyList<string> Paragraphs, string Reference)
    {
        public string Body => string.Join("\n", Paragraphs);
    }

    /// <summary>
    /// The rulebook as it is shown inside the game. Content follows the Russian translation of the WMCC
    /// rules in the repository (`docs/rule-text.md`) and states its own simplifications honestly: a page
    /// is a reading of the rule, not a replacement for it.
    ///
    /// Plain C#, no Unity, so the self-test can check that every page exists, is filled and points at a
    /// real rule number, and the Unity panel only has to lay the pages out.
    /// </summary>
    public static class RulesBook
    {
        public static IReadOnlyList<RulesSection> Sections { get; } = BuildSections();

        public static RulesSection? Find(string id) => Sections.FirstOrDefault(section => section.Id == id);

        /// <summary>The fan table of 3.8.1 as a page: points, name, and how many entries carry that value.</summary>
        public static IReadOnlyList<string> FanTable()
        {
            var lines = new List<string>();
            foreach (var group in Fans.All.GroupBy(fan => fan.Points).OrderByDescending(group => group.Key))
                lines.Add($"{group.Key} очк. — {string.Join(", ", group.Select(fan => fan.NameRu))}");
            return lines;
        }

        public static string FanTableText() => string.Join("\n", FanTable());

        /// <summary>Number of pages, for "page N of M" captions.</summary>
        public static int Count => Sections.Count;

